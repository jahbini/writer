#!/usr/bin/env bash
#
# model.sh — set up a HuggingFace model into a pipe's build/ dir via
# the download_model recipe.
#
# Usage:
#   npm run model -- <pipe> <org/modelname>
#   ./bin/model.sh <pipe> <org/modelname>
#
# Example:
#   npm run model -- diary Qwen/Qwen3-4B-Instruct-2507
#
# Writes a fresh `override.yaml` inside pipes/<pipe>/ selecting
# `pipeline: download_model`, then runs `npx pipeline` from that pipe.
# The recipe downloads to pipes/<pipe>/build/model/ and quantizes into
# pipes/<pipe>/build/model4/.
#
# Existing pipes/<pipe>/override.yaml is backed up with a timestamp
# before being replaced.
#
set -euo pipefail
cd "$(dirname "$0")/.."

PIPE="${1:-}"
MODEL="${2:-}"
if [ -z "$PIPE" ] || [ -z "$MODEL" ]; then
  echo "Usage: npm run model -- <pipe> <org/modelname>"
  echo "       e.g. npm run model -- diary Qwen/Qwen3-4B-Instruct-2507"
  exit 1
fi

PIPE_DIR="pipes/$PIPE"
if [ ! -d "$PIPE_DIR" ]; then
  echo "Error: $PIPE_DIR does not exist. Create it with: npm run pipe:new $PIPE"
  exit 1
fi

if [ ! -d .venv ]; then
  echo "Error: .venv not found. Run ./run-first.sh first."
  exit 1
fi

# Back up any existing per-pipe override.yaml.
if [ -f "$PIPE_DIR/override.yaml" ]; then
  mv "$PIPE_DIR/override.yaml" "$PIPE_DIR/override.yaml.$(date +%Y-%m-%d_%H-%M-%S).bak"
fi

# Write a fresh override pointed at the download_model recipe.
cat > "$PIPE_DIR/override.yaml" <<EOF
# Generated by \`npm run model\`. Edit freely.
pipeline: download_model

download_model:
  model: $MODEL
  # download_dir: build/model       # default (pipe-local)
  # quantized_dir: build/model4     # default (pipe-local)
  # q_bits: 4                       # default
EOF

echo "Wrote $PIPE_DIR/override.yaml selecting pipeline: download_model for $MODEL"
echo
echo "Running pipeline — this will download (~5-10 min for a 4B model)"
echo "                   then quantize (~1-2 min)..."
echo
cd "$PIPE_DIR"
exec npx pipeline
