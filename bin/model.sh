#!/usr/bin/env bash
#
# model.sh — set up a HuggingFace model via the download_model recipe.
#
# Usage:
#   npm run model -- <org/modelname>
#   ./bin/model.sh <org/modelname>
#
# Example:
#   npm run model -- Qwen/Qwen3-4B-Instruct-2507
#
# What it does: writes a fresh `override.yaml` at the project root
# selecting `pipeline: download_model` and naming the model, then
# invokes `npx pipeline`. The recipe (shipped with @jahbini/pipeline)
# downloads the model into build/model/ and quantizes it into
# build/model4/. The quantized output is self-contained and needs
# no further HF network access.
#
# Existing project-root override.yaml is backed up with a timestamp
# before being replaced (override.yaml.YYYY-MM-DD_HH-MM-SS.bak).
# Per-pipe override.yamls under pipes/*/ are untouched.
#
set -euo pipefail
cd "$(dirname "$0")/.."

MODEL="${1:-}"
if [ -z "$MODEL" ]; then
  echo "Usage: npm run model -- <org/modelname>"
  echo "       e.g. npm run model -- Qwen/Qwen3-4B-Instruct-2507"
  exit 1
fi

if [ ! -d .venv ]; then
  echo "Error: .venv not found. Run ./run-first.sh first."
  exit 1
fi

# Back up any existing project-root override.yaml.
if [ -f override.yaml ]; then
  mv override.yaml "override.yaml.$(date +%Y-%m-%d_%H-%M-%S).bak"
fi

# Write a fresh override pointed at the download_model recipe.
cat > override.yaml <<EOF
# Generated by \`npm run model\`. Edit freely.
pipeline: download_model

download_model:
  model: $MODEL
  # download_dir: build/model       # default
  # quantized_dir: build/model4     # default
  # q_bits: 4                       # default
EOF

echo "Wrote override.yaml selecting pipeline: download_model for $MODEL"
echo
echo "Running pipeline — this will download (~5-10 min for a 4B model)"
echo "                   then quantize (~1-2 min)..."
echo
exec npx pipeline
